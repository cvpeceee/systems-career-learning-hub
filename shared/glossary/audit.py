def terms_in(text):
    hits={}
    for m in re.finditer(r'(?<![A-Za-z0-9_])([A-Z][A-Za-z0-9]*[A-Z0-9][A-Za-z0-9]*|[a-z]{1,2}[A-Z]{2,}[A-Za-z0-9]*)(?![A-Za-z0-9_])',text):
        t=m.group(1); base=re.sub(r's$','',t) if len(t)>3 and t.endswith('s') and t[:-1].isupper() else t
        if base in STOP or len(base)<2 or not re.search(r'[A-Z]{2}|[a-z][A-Z]|[A-Z][0-9]',base): continue
        if re.fullmatch(r'[A-Z][0-9]+|[A-Z]{1,2}[0-9]{1,2}[a-z]?|[0-9A-F]{4,}|[A-Z]{5,}',base) and base.lower() not in GL: continue  # labels like P1, L3, hex, SHOUTING
        hits.setdefault(base,m.start())
    for k in GL:
        if k[0].islower():
            m=re.search(r'(?<![A-Za-z0-9_])'+re.escape(k)+r'(s|es)?(?![A-Za-z0-9_])',text,re.I)
            if m: hits.setdefault(GL[k]['t'],m.start())
    return hits
def inline_defined(text,t,pos):
    after=text[pos+len(t):pos+len(t)+70]; before=text[max(0,pos-80):pos]
    if re.match(r"s?\s*(\(|:|—|–| - | = |,? (is|are|means|stands for|short for)\b|,? (a|an|the) [a-z])",after): return True
    if re.search(r'\(\s*$',before) and re.match(r's?\)',after): return True     # Full Name (ACR)
    if re.search(r'(called|known as|named)\s+["“]?$',before): return True
    return False
def audit_units(units,covered_fn):
    rep=[];tot=collections.Counter()
    for u in units:
        text=u['text']; hits=terms_in(text); und_b=[];und_a=[]
        for t,pos in sorted(hits.items(),key=lambda x:x[1]):
            d=inline_defined(text,t,pos); tot['terms']+=1
            if not d: und_b.append(t)
            if not d and not covered_fn(u,t): und_a.append(t)
        tot['undef_before']+=len(und_b); tot['undef_after']+=len(und_a); rep.append((u,und_b,und_a))
    return rep,tot
def gloss_has(t): return t.lower() in GL or re.sub(r'e?s$','',t.lower()) in GL
def main():
    crawl=json.load(open(H+'/qa/crawl.json'))
    seen=set(); units=[]
    for u in crawl:
        k=(u['file'],u['text'][:200]);
        if k in seen or len(u['text'])<200: continue
        seen.add(k); units.append(u)
    vt=[]
    for f in sorted(glob.glob(R+'/0[46]*/videos/**/*.vtt',recursive=True)):
        s=open(f).read(); txt=' '.join(l for l in s.split('\n') if l and '-->' not in l and l!='WEBVTT' and not l.strip().isdigit())
        vt.append(dict(file=os.path.relpath(f,R),unit=os.path.basename(f),text=txt))
    out=['# Jargon audit (first-use check)','',
      'Generated by `shared/glossary/audit.py` from a headless-Chrome crawl of every lesson/page (`qa/crawl.js`) and every video transcript.',
      '**Before** = term not explained where it first appears. **After** = still unexplained after the fix (no inline meaning AND no glossary chip / term card).',
      f'Shared glossary: {len(G)} terms (`shared/glossary/glossary.json`), same definitions in every course.','']
    summary=[]; detail=[]
    byfile=collections.defaultdict(list)
    for u in units: byfile[u['file']].append(u)
    for u in vt: byfile[u['file'].rsplit('/',1)[0]+'/ (videos)'].append(u)
    gaps=collections.Counter()
    for f,us in byfile.items():
        isv='(videos)' in f
        cov=(lambda u,t: gloss_has(t)) if isv else (lambda u,t: t.lower() in {c.lower() for c in u.get('chips',[])} or gloss_has(t))
        rep,tot=audit_units(us,cov)
        summary.append(f'| {f} | {len(us)} | {tot["terms"]} | {tot["undef_before"]} | {tot["undef_after"]} |')
        detail.append(f'\n## {f}\n')
        for u,b,a in rep:
            for t in a: gaps[t]+=1
            if b: detail.append(f'- **{u["unit"][:90]}** — before ({len(b)}): {", ".join(b[:25])}{" …" if len(b)>25 else ""}' + (f' → after ({len(a)}): {", ".join(a[:15])}' if a else ' → after: 0'))
    out+=['| Course / file | units | first-use terms | undefined BEFORE | undefined AFTER |','|---|---|---|---|---|']+summary
    out+=['','### Most common remaining undefined terms (after)','',', '.join(f'{t} ({n})' for t,n in gaps.most_common(80)) or 'none']
    out+=detail
    open(R+'/docs/JARGON_AUDIT.md','w').write('\n'.join(out)+'\n'); print('\n'.join(summary)); print(gaps.most_common(120))
if __name__=='__main__': main()
